def body(relative):
    text = (DOCS / relative).read_text()
    return re.sub(r'^---\n.*?\n---\n', '', text, count=1, flags=re.S).strip()


def reference(paths):
    return '\n\n'.join(body(p) for p in paths) + '\n'


