tex = tex.replace('\\setcounter{tocdepth}{2}', '\\setcounter{tocdepth}{1}')
p.write_text('% Generated from canonical MDX by scripts/generate-doc-artifacts.py.\n' + tex)
(ROOT/'public/whitepaper.tex').write_text(p.read_text())
